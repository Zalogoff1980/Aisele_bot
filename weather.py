# GET WEATHER
# ============================================================

def get_weather(
    location,
    days=3,
):

    place = geocode_location(
        location
    )

    if not place:

        return {
            "success": False,
            "error": (
                f"Не удалось найти место: "
                f"{location}"
            ),
        }

    latitude = place.get(
        "latitude"
    )

    longitude = place.get(
        "longitude"
    )

    if (
        latitude is None
        or longitude is None
    ):

        return {
            "success": False,
            "error": (
                f"Не удалось определить "
                f"координаты {location}."
            ),
        }

    try:

        weather = get_json(
            WEATHER_URL,
            {

                "latitude": latitude,

                "longitude": longitude,

                "current": (
                    "temperature_2m,"
                    "relative_humidity_2m,"
                    "apparent_temperature,"
                    "precipitation,"
                    "weather_code,"
                    "cloud_cover,"
                    "wind_speed_10m,"
                    "wind_gusts_10m"
                ),

                "daily": (
                    "weather_code,"
                    "temperature_2m_max,"
                    "temperature_2m_min,"
                    "precipitation_probability_max,"
                    "precipitation_sum,"
                    "wind_speed_10m_max"
                ),

                "forecast_days": max(
                    3,
                    min(
                        int(days),
                        7,
                    ),
                ),

                "timezone": "auto",
            },
        )

    except Exception:

        return {
            "success": False,
            "error": (
                "Не удалось получить "
                "данные о погоде прямо сейчас."
            ),
        }

    return {

        "success": True,

        "location": {

            "name": place.get(
                "name",
                location,
            ),

            "country": place.get(
                "country",
                "",
            ),

            "region": place.get(
                "admin1",
                "",
            ),

            "latitude": latitude,

            "longitude": longitude,

            "timezone": place.get(
                "timezone",
                "auto",
            ),
        },

        "current": weather.get(
            "current",
            {},
        ),

        "daily": weather.get(
            "daily",
            {},
        ),

        "hourly": weather.get(
            "hourly",
            {},
        ),
    }


