# ============================================================
# GEOCODING
# ============================================================

def geocode_location(location):

    normalized = normalize_location(
        location
    )

    if not normalized:
        return None

    # --------------------------------------------------------
    # Основной запрос
    # --------------------------------------------------------

    try:

        data = get_json(
            GEOCODING_URL,
            {
                "name": normalized,
                "count": 10,
                "language": "ru",
                "format": "json",
            },
        )

    except Exception:

        return None

    results = data.get(
        "results",
        [],
    )

    if not results:
        return None

    target = normalized.lower()

    # --------------------------------------------------------
    # Сначала точное совпадение
    # --------------------------------------------------------

    for result in results:

        name = (
            result.get("name")
            or ""
        ).strip().lower()

        if name == target:
            return result

    # --------------------------------------------------------
    # Затем страна пользователя / наиболее вероятная страна
    # --------------------------------------------------------

    # Узбекистан
    uzbekistan = [
        result
        for result in results
        if (
            result.get(
                "country_code"
            )
            or ""
        ).lower() == "uz"
    ]

    if uzbekistan:
        return uzbekistan[0]

    # Россия
    russia = [
        result
        for result in results
        if (
            result.get(
                "country_code"
            )
            or ""
        ).lower() == "ru"
    ]

    if russia:
        return russia[0]

    # Украина
    ukraine = [
        result
        for result in results
        if (
            result.get(
                "country_code"
            )
            or ""
        ).lower() == "ua"
    ]

    if ukraine:
        return ukraine[0]

    return results[0]


