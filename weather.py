# ============================================================
# HTTP
# ============================================================

def get_json(url, params):

    query = urlencode(params)

    request = Request(
        f"{url}?{query}",
        headers={
            "User-Agent": "AiseleBot/1.0"
        },
    )

    with urlopen(
        request,
        timeout=15,
    ) as response:

        return json.loads(
            response.read()
        )


