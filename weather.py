# WEATHER REQUEST DETECTION
# ============================================================

def is_weather_request(text):

    text = (
        text or ""
    ).strip().lower()

    if not text:
        return False

    weather_words = (
        "погод",
        "температур",
        "дожд",
        "снег",
        "ветер",
        "облачн",
        "осадк",
        "градус",
        "тепло",
        "холодно",
        "жара",
        "мороз",
        "гроза",
    )

    if any(
        word in text
        for word in weather_words
    ):
        return True

    relative_words = (
        "а завтра",
        "завтра",
        "а послезавтра",
        "послезавтра",
        "на завтра",
        "на послезавтра",
        "а сегодня",
        "сегодня",
        "на сегодня",
    )

    if any(
        phrase in text
        for phrase in relative_words
    ):
        return True

    # --------------------------------------------------------
    # Короткие запросы:
    #
    # А в Воронеже?
    # В Москве?
    # А в Новороссийске?
    # На Кубани?
    # --------------------------------------------------------

    city_request = re.match(
        r"^\s*"
        r"(?:а\s+)?"
        r"(?:в|во|на)\s+"
        r".+?"
        r"\s*[?!.,]*"
        r"\s*$",
        text,
        flags=re.IGNORECASE,
    )

    if city_request:
        return True

    return False


# ============================================================
# LOCATION EXTRACTION
# ============================================================

def extract_weather_location(text):

    text = (
        text or ""
    ).strip()

    if not text:
        return None

    cleaned = re.sub(
        r"[?.!,;:]+$",
        "",
        text,
    ).strip()

    # ========================================================
    # КОРОТКИЕ ЗАПРОСЫ
    #
    # "А в Воронеже?"
    # "В Москве?"
    # "А в Новороссийске?"
    # "На Кубани?"
    # ========================================================

    match = re.match(
        r"^\s*"
        r"(?:а\s+)?"
        r"(?:в|во|на)\s+"
        r"(?:городе\s+)?"
        r"(.+?)"
        r"\s*$",
        cleaned,
        flags=re.IGNORECASE,
    )

    if match:

        location = (
            match.group(1)
            or ""
        ).strip()

        if location:

            return normalize_location(
                location
            )

    # ========================================================
    # ОБЫЧНЫЕ ЗАПРОСЫ
    # ========================================================

    patterns = (

        r"(?:погода|температура|температуру|ветер|дождь|снег)"
        r".*?"
        r"(?:в|во|на)\s+"
        r"(?:городе\s+)?"
        r"(.+)$",

        r"(?:какая|какой|какое)"
        r".*?"
        r"(?:погода|температура)"
        r".*?"
        r"(?:в|во|на)\s+"
        r"(?:городе\s+)?"
        r"(.+)$",

        # "Что с погодой в Новороссийске?"
        r"(?:что\s+с\s+)?"
        r"(?:погодой|погодка)"
        r".*?"
        r"(?:в|во|на)\s+"
        r"(?:городе\s+)?"
        r"(.+)$",
    )

    for pattern in patterns:

        match = re.search(
            pattern,
            cleaned,
            flags=re.IGNORECASE,
        )

        if match:

            location = (
                match.group(1)
                or ""
            ).strip()

            location = re.sub(
                r"[?.!,;:]+$",
                "",
                location,
            ).strip()

            if location:

                return normalize_location(
                    location
                )

    # ========================================================
    # "погода города Воронеж"
    # ========================================================

    match = re.search(
        r"(?:погода|температура)"
        r"\s+города\s+(.+)$",
        cleaned,
        flags=re.IGNORECASE,
    )

    if match:

        location = (
            match.group(1)
            or ""
        ).strip()

        if location:

            return normalize_location(
                location
            )

    return None


