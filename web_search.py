from openai import OpenAI

from config import OPENAI_API_KEY, AI_MODEL


client = OpenAI(
    api_key=OPENAI_API_KEY
)


WEB_SEARCH_INSTRUCTIONS = """
Ты — Айсель, AI-компаньон.

Твоя задача — отвечать пользователю естественно и по-русски,
но при необходимости использовать интернет.

Когда используешь интернет:

1. Ищи актуальную информацию.
2. Предпочитай первичные источники:
   официальные сайты, документы, исследования,
   заявления компаний, GitHub, государственные источники.
3. Для спорных или быстро меняющихся фактов
   используй несколько независимых источников.
4. Не выдавай предположение за установленный факт.
5. Если нормального подтверждения нет — прямо скажи об этом.
6. Не пересказывай поисковую выдачу.
7. Отвечай своими словами, анализируя найденную информацию.
8. В конце обязательно добавляй раздел:

Источники:
- название источника — URL

Используй только реально найденные источники.
Не выдумывай URL.

Если вопрос не требует свежей информации,
не используй интернет.
"""


def web_search_reply(
    text,
    context_text="",
):
    """
    Выполняет поиск в интернете и возвращает
    готовый ответ Айсель.
    """

    prompt = text

    if context_text:
        prompt = (
            "Контекст предыдущего разговора:\n"
            + context_text
            + "\n\n"
            "Новый вопрос пользователя:\n"
            + text
        )

    response = client.responses.create(
        model=AI_MODEL,
        tools=[
            {
                "type": "web_search",
                "search_context_size": "medium",
            }
        ],
        instructions=WEB_SEARCH_INSTRUCTIONS,
        input=prompt,
    )

    answer = (
        response.output_text
        or ""
    ).strip()

    return answer

